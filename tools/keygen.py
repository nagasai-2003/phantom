#!/usr/bin/env python3
"""Phantom access-code generator.

Codes are signed with an Ed25519 private key that stays on your Mac. The app only
contains the public key, so it can check a code but nobody can make new ones.

  python3 tools/keygen.py init                  # once: create your key pair
  python3 tools/keygen.py generate              # 10 codes, 3 hours each, redeem within 7 days
  python3 tools/keygen.py generate --count 5 --hours 2 --valid-days 30
  python3 tools/keygen.py check PH1-...         # see what a code contains

Code layout (base32 after "PH1-"):
  8 bytes  random code id (the app refuses an id it has already used)
  1 byte   unlock hours
  4 bytes  redeem-by time, unix seconds, big-endian (0 = no limit)
  64 bytes Ed25519 signature over b"PH1" + the 13 bytes above
"""
import argparse
import base64
import csv
import os
import secrets
import struct
import sys
import time
from datetime import datetime
from pathlib import Path

from cryptography.exceptions import InvalidSignature
from cryptography.hazmat.primitives import serialization
from cryptography.hazmat.primitives.asymmetric.ed25519 import Ed25519PrivateKey, Ed25519PublicKey

PREFIX = "PH1"
KEY_DIR = Path(os.environ.get("PHANTOM_KEY_DIR", Path.home() / ".phantom-keys"))
PRIVATE_KEY = KEY_DIR / "private_key.pem"
ISSUED_LOG = KEY_DIR / "issued_codes.csv"
SWIFT_KEY_FILE = Path(__file__).resolve().parent.parent / "Sources/Phantom/Config/AccessPublicKey.swift"


def b32(data: bytes) -> str:
    return base64.b32encode(data).decode().rstrip("=")


def unb32(text: str) -> bytes:
    return base64.b32decode(text + "=" * (-len(text) % 8))


def load_private_key() -> Ed25519PrivateKey:
    if not PRIVATE_KEY.exists():
        sys.exit(f"No key found at {PRIVATE_KEY}. Run: python3 tools/keygen.py init")
    return serialization.load_pem_private_key(PRIVATE_KEY.read_bytes(), password=None)


def public_bytes(key) -> bytes:
    return key.public_key().public_bytes(serialization.Encoding.Raw, serialization.PublicFormat.Raw)


def write_swift_key(pub: bytes) -> None:
    body = ", ".join(f"0x{b:02x}" for b in pub)
    SWIFT_KEY_FILE.write_text(
        "// Generated by tools/keygen.py init. Public key only; safe to commit.\n"
        f"let accessPublicKey: [UInt8] = [{body}]\n"
    )


def cmd_init(args) -> None:
    if PRIVATE_KEY.exists() and not args.force:
        sys.exit(f"A key already exists at {PRIVATE_KEY}. Codes made with it would stop working "
                 "if you replace it. Use --force only if you really want a new key.")
    KEY_DIR.mkdir(mode=0o700, parents=True, exist_ok=True)
    key = Ed25519PrivateKey.generate()
    PRIVATE_KEY.write_bytes(key.private_bytes(serialization.Encoding.PEM,
                                              serialization.PrivateFormat.PKCS8,
                                              serialization.NoEncryption()))
    PRIVATE_KEY.chmod(0o600)
    write_swift_key(public_bytes(key))
    print(f"Private key saved to {PRIVATE_KEY}  (keep it secret, back it up, never commit it)")
    print(f"Public key written to {SWIFT_KEY_FILE}  (rebuild the app to use it)")


def make_code(key: Ed25519PrivateKey, hours: int, redeem_by: int) -> tuple[str, str]:
    code_id = secrets.token_bytes(8)
    payload = code_id + struct.pack(">BI", hours, redeem_by)
    sig = key.sign(PREFIX.encode() + payload)
    return f"{PREFIX}-{b32(payload + sig)}", code_id.hex()


def cmd_generate(args) -> None:
    if not 1 <= args.hours <= 255:
        sys.exit("--hours must be between 1 and 255")
    key = load_private_key()
    now = int(time.time())
    redeem_by = now + args.valid_days * 86400 if args.valid_days > 0 else 0
    rows = []
    for _ in range(args.count):
        code, code_id = make_code(key, args.hours, redeem_by)
        rows.append((code_id, datetime.fromtimestamp(now).isoformat(timespec="seconds"),
                     datetime.fromtimestamp(redeem_by).isoformat(timespec="seconds") if redeem_by else "never",
                     args.hours, code))
        print(code)
    new_log = not ISSUED_LOG.exists()
    with ISSUED_LOG.open("a", newline="") as f:
        w = csv.writer(f)
        if new_log:
            w.writerow(["code_id", "issued", "redeem_by", "hours", "code"])
        w.writerows(rows)
    until = rows[0][2] if redeem_by else "any time"
    print(f"\n{args.count} codes · {args.hours} h each · redeem by {until} · logged to {ISSUED_LOG}",
          file=sys.stderr)


def cmd_check(args) -> None:
    key = load_private_key().public_key()
    text = "".join(args.code.split()).upper()
    if not text.startswith(PREFIX + "-"):
        sys.exit("Not a Phantom code (should start with PH1-)")
    raw = unb32(text[len(PREFIX) + 1:])
    if len(raw) != 13 + 64:
        sys.exit("Wrong length")
    payload, sig = raw[:13], raw[13:]
    try:
        key.verify(sig, PREFIX.encode() + payload)
    except InvalidSignature:
        sys.exit("Signature INVALID — not made with your key")
    hours, redeem_by = struct.unpack(">BI", payload[8:])
    print(f"valid · id {payload[:8].hex()} · {hours} h · redeem by "
          f"{datetime.fromtimestamp(redeem_by) if redeem_by else 'never'}")


def main() -> None:
    p = argparse.ArgumentParser(description="Phantom access-code generator")
    sub = p.add_subparsers(dest="cmd", required=True)
    i = sub.add_parser("init", help="create your signing key pair (once)")
    i.add_argument("--force", action="store_true", help="replace an existing key")
    g = sub.add_parser("generate", help="make new codes")
    g.add_argument("--count", type=int, default=10)
    g.add_argument("--hours", type=int, default=3, help="unlock time per code")
    g.add_argument("--valid-days", type=int, default=7, help="days to redeem; 0 = no limit")
    c = sub.add_parser("check", help="inspect a code")
    c.add_argument("code")
    args = p.parse_args()
    {"init": cmd_init, "generate": cmd_generate, "check": cmd_check}[args.cmd](args)


if __name__ == "__main__":
    main()
